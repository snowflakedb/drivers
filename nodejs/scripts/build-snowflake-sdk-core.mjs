/* oxlint-disable no-console */
import { NapiCli } from '@napi-rs/cli';
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs/promises';
import { tmpdir } from 'node:os';
import * as path from 'node:path';
import {
  BUILD_CORE_PACKAGE_DIR,
  BUILD_DIR,
  NODE_SDK_PACKAGE,
  NODE_SDK_PACKAGE_JSON_PATH,
  ROOT_DIR,
} from './common.mjs';

const NAPI_CONFIG = NODE_SDK_PACKAGE.napi;
const BUILD_PLACEHOLDER_PACKAGES_DIR = path.join(BUILD_DIR, 'napi-placeholder-packages');
const fipsBuild = process.env.SF_CORE_FIPS?.toLowerCase();
const buildWithFips = fipsBuild === '1' || fipsBuild === 'true';
// Release builds are opt-in; local development and existing test jobs stay debug.
const releaseBuild = process.env.SF_CORE_RELEASE?.toLowerCase();
const buildRelease = releaseBuild === '1' || releaseBuild === 'true';
const linkerMap = process.env.SF_CORE_LINKER_MAP;
if (linkerMap && (process.platform !== 'win32' || !buildRelease)) {
  throw new Error('SF_CORE_LINKER_MAP requires Windows and SF_CORE_RELEASE=1');
}
const manifestPath = path.join(ROOT_DIR, '..', 'nodejs_bridge', 'Cargo.toml');
const cargoOptions = buildWithFips ? ['--locked', '--features', 'fips'] : ['--locked'];

// Compiles the `nodejs_bridge` Rust crate directly into the linkable platform
// package at `_build/<napi.packageName>/` (i.e. `_build/snowflake-sdk-core/`),
// then splits the napi outputs into their two homes:
//   - The generated `.d.ts` (the crate's TypeScript API) is MOVED out of the
//     built platform package into the committed source tree as
//     `src/core/binary-types.generated.ts` (renamed `.d.ts` -> `.ts` so `tsc`
//     emits it into `dist/`). This is what lets the loader type `getCore()`
//     against the native API regardless of which per-platform binary package is
//     installed at runtime.
//   - The platform-specific `.node` binary stays in the package alongside a
//     copied-in `snowflake-sdk-core-<triple>` `package.json` (os/cpu guards,
//     `main`/`files` pointing at the `.node`).
//
// The build runs as the numbered steps marked below.

// 1. Remove the package dir so stale artifacts can't survive across builds.
console.log('Clearing build directory', BUILD_CORE_PACKAGE_DIR);
await fs.rm(BUILD_CORE_PACKAGE_DIR, { recursive: true, force: true });

// 2. Build the crate directly into the package dir:
//    - `platform: true` names the `.node` file per host target.
//    - `noJsBinding: true` skips the generated JS loader shim, so the `.d.ts` is
//      the only JS-facing artifact.
const cli = new NapiCli();
const { task } = await cli.build({
  platform: true,
  release: buildRelease,
  cargoName: 'nodejs_bridge',
  manifestPath,
  packageJsonPath: NODE_SDK_PACKAGE_JSON_PATH,
  outputDir: BUILD_CORE_PACKAGE_DIR,
  cwd: ROOT_DIR,
  cargoOptions,
  noJsBinding: true,
  dtsHeader: `\
/**
 * AUTO-GENERATED - DO NOT EDIT.
 * Native binary types produced by "napi build"
 *
 * Generated by scripts/build-snowflake-sdk-core.mjs
 */
`,
});
await task;

// 3. Finalize the package from the produced artifacts:
//    - Read the platform triple back from the `.node` filename.
//    - Move the generated `.d.ts` out of the package into the committed source
//      tree as `src/core/binary-types.generated.ts`, renamed to `.ts` so `tsc`
//      emits it into `dist/`.
//    - Run `napi create-npm-dirs`, which writes one subdir per configured target
//      under `BUILD_PLACEHOLDER_PACKAGES_DIR`, each holding a placeholder
//      package.json for that platform's N-API package (os/cpu guards); then copy
//      only the host target's manifest into the package.
const producedFiles = await fs.readdir(BUILD_CORE_PACKAGE_DIR);
const binaryFileName = producedFiles.find((file) => file.endsWith('.node'));
const dtsFileName = producedFiles.find((file) => file.endsWith('.d.ts'));
if (linkerMap) {
  // napi invokes cargo build, which cannot forward final-crate rustc arguments.
  // A unique /MAP argument forces a fresh final link even on a Cargo cache hit.
  const mapPath = path.resolve(linkerMap);
  await fs.mkdir(path.dirname(mapPath), { recursive: true });
  const mapDirectory = await fs.mkdtemp(path.join(tmpdir(), 'snowflake-sdk-core-map-'));
  const freshMapPath = path.join(mapDirectory, 'nodejs_bridge.map');
  try {
    const compilerOutput = execFileSync(
      process.env.CARGO ?? 'cargo',
      [
        'rustc',
        '--release',
        '--lib',
        '--package',
        'nodejs_bridge',
        '--manifest-path',
        manifestPath,
        '--message-format=json-render-diagnostics',
        ...cargoOptions,
        '--',
        '-C',
        `link-arg=/MAP:${freshMapPath}`,
      ],
      {
        cwd: ROOT_DIR,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'inherit'],
        maxBuffer: 16 * 1024 * 1024,
      },
    );
    let dllPath;
    for (const line of compilerOutput.trim().split('\n')) {
      const message = JSON.parse(line);
      if (message.reason === 'compiler-artifact' && message.target.name === 'nodejs_bridge') {
        dllPath = message.filenames.find((file) => file.endsWith('.dll'));
      }
    }
    if (!dllPath) {
      throw new Error('cargo rustc did not report the mapped nodejs_bridge DLL');
    }
    // A missing fresh map must fail, never reuse an older map at the requested path.
    await fs.copyFile(freshMapPath, mapPath);
    await fs.copyFile(dllPath, path.join(BUILD_CORE_PACKAGE_DIR, binaryFileName));
  } finally {
    await fs.rm(mapDirectory, { recursive: true, force: true });
  }
}
const platformTriple = binaryFileName.slice(`${NAPI_CONFIG.binaryName}.`.length, -'.node'.length);
// TODO: Consider enforcing a merge gate to ensure the committed declaration file
// stays in sync with the current nodejs_bridge state in git
await fs.rename(
  path.join(BUILD_CORE_PACKAGE_DIR, dtsFileName),
  path.join(ROOT_DIR, 'src', 'core', 'binary-types.generated.ts'),
);
// TODO: We might want to optimize this in the future so createNpmDirs isn't called on every build
await cli.createNpmDirs({
  packageJsonPath: NODE_SDK_PACKAGE_JSON_PATH,
  npmDir: BUILD_PLACEHOLDER_PACKAGES_DIR,
  cwd: ROOT_DIR,
});
await fs.copyFile(
  path.join(BUILD_PLACEHOLDER_PACKAGES_DIR, platformTriple, 'package.json'),
  path.join(BUILD_CORE_PACKAGE_DIR, 'package.json'),
);

// 4. Log the build output
console.log(`build -> _build/${NAPI_CONFIG.packageName}/ (snowflake-sdk-core-${platformTriple})`);
for (const file of await fs.readdir(BUILD_CORE_PACKAGE_DIR)) {
  console.log(`  ${file}`);
}
