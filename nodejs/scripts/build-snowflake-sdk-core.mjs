/* oxlint-disable no-console */
import { NapiCli } from '@napi-rs/cli';
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import * as url from 'node:url';

// Compiles the `nodejs_bridge` Rust crate directly into the linkable platform
// package at `_build/<napi.packageName>/` (i.e. `_build/snowflake-sdk-core/`),
// then splits the napi outputs into their two homes:
//   - The generated `.d.ts` (the crate's TypeScript API) is MOVED out of the
//     built platform package into the committed source tree as
//     `src/core/binary-types.generated.ts` (renamed `.d.ts` -> `.ts` so `tsc`
//     emits it into `dist/`). This is what lets the loader type `getCore()`
//     against the native API regardless of which per-platform binary package is
//     installed at runtime.
//   - The platform-specific `.node` binary stays in the package alongside a
//     copied-in `snowflake-sdk-core-<triple>` `package.json` (os/cpu guards,
//     `main`/`files` pointing at the `.node`).
//
// The build runs as the numbered steps marked below.

// 1. Read the `napi` config (packageName/binaryName/targets) from the SDK's
//    package.json and derive the output paths.
const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const NODE_SDK_PACKAGE_JSON_PATH = path.join(ROOT_DIR, 'package.json');
const { napi: NAPI_CONFIG } = JSON.parse(await fs.readFile(NODE_SDK_PACKAGE_JSON_PATH, 'utf8'));
const BUILD_DIR = path.join(ROOT_DIR, '_build');
const BUILD_PLACEHOLDER_PACKAGES_DIR = path.join(BUILD_DIR, 'napi-placeholder-packages');
const BUILD_CORE_PACKAGE_DIR = path.join(BUILD_DIR, NAPI_CONFIG.packageName);

// 2. Remove the package dir so stale artifacts can't survive across builds.
await fs.rm(BUILD_CORE_PACKAGE_DIR, { recursive: true, force: true });

// 3. Build the crate directly into the package dir:
//    - `platform: true` names the `.node` file per host target.
//    - `noJsBinding: true` skips the generated JS loader shim, so the `.d.ts` is
//      the only JS-facing artifact.
const cli = new NapiCli();
const { task } = await cli.build({
  platform: true,
  release: true,
  cargoName: 'nodejs_bridge',
  manifestPath: path.join(ROOT_DIR, '..', 'nodejs_bridge', 'Cargo.toml'),
  packageJsonPath: NODE_SDK_PACKAGE_JSON_PATH,
  outputDir: BUILD_CORE_PACKAGE_DIR,
  cwd: ROOT_DIR,
  noJsBinding: true,
  dtsHeader: `\
/**
 * AUTO-GENERATED - DO NOT EDIT.
 * Native binary types produced by "napi build"
 *
 * Generated by scripts/build-snowflake-sdk-core.mjs
 */
`,
});
await task;

// 4. Finalize the package from the produced artifacts:
//    - Read the platform triple back from the `.node` filename.
//    - Move the generated `.d.ts` out of the package into the committed source
//      tree as `src/core/binary-types.generated.ts`, renamed to `.ts` so `tsc`
//      emits it into `dist/`.
//    - Run `napi create-npm-dirs`, which writes one subdir per configured target
//      under `BUILD_PLACEHOLDER_PACKAGES_DIR`, each holding a placeholder
//      package.json for that platform's N-API package (os/cpu guards); then copy
//      only the host target's manifest into the package.
const producedFiles = await fs.readdir(BUILD_CORE_PACKAGE_DIR);
const binaryFileName = producedFiles.find((file) => file.endsWith('.node'));
const dtsFileName = producedFiles.find((file) => file.endsWith('.d.ts'));
const platformTriple = binaryFileName.slice(`${NAPI_CONFIG.binaryName}.`.length, -'.node'.length);
await fs.rename(
  path.join(BUILD_CORE_PACKAGE_DIR, dtsFileName),
  path.join(ROOT_DIR, 'src', 'core', 'binary-types.generated.ts'),
);
// TODO: We might want to optimize this in the future so createNpmDirs isn't called on every build
await cli.createNpmDirs({
  packageJsonPath: NODE_SDK_PACKAGE_JSON_PATH,
  npmDir: BUILD_PLACEHOLDER_PACKAGES_DIR,
  cwd: ROOT_DIR,
});
await fs.copyFile(
  path.join(BUILD_PLACEHOLDER_PACKAGES_DIR, platformTriple, 'package.json'),
  path.join(BUILD_CORE_PACKAGE_DIR, 'package.json'),
);

// 5. Link the platform package into ROOT_DIR's node_modules so the loader can
//    resolve `snowflake-sdk-core-${platformTriple}` during local development.
execFileSync('npm', ['link', BUILD_CORE_PACKAGE_DIR], {
  cwd: ROOT_DIR,
  stdio: 'inherit',
});

// 6. Log the build output
console.log(`build -> _build/${NAPI_CONFIG.packageName}/ (snowflake-sdk-core-${platformTriple})`);
for (const file of await fs.readdir(BUILD_CORE_PACKAGE_DIR)) {
  console.log(`  ${file}`);
}
