using System.Reflection;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Snowflake.Data.Tests.ArchitectureInvariantTests.Metadata;
using Snowflake.Data.Tests.Compatibility;
using AssemblyMetadata = Snowflake.Data.Tests.ArchitectureInvariantTests.Metadata.AssemblyMetadata;

namespace Snowflake.Data.Tests.ArchitectureInvariantTests.Utils;

public static class AssemblyUtil
{
    internal static string SolutionRoot { get; } = FindSolutionRoot();

    private static string OutputSubdirectory { get; } = FindOutputSubdirectory();

    internal static IEnumerable<(string RelativePath, SyntaxNode Root)> GetSyntaxRoots(Metadata.AssemblyMetadata assemblyMetadata)
    {
        var assemblyName = assemblyMetadata.ProjectName;
        var path = assemblyName.Contains("Tests")
            ? Path.Combine(SolutionRoot, "tests", assemblyName)
            : Path.Combine(SolutionRoot, "src", assemblyName);
        var csFiles = Directory.GetFiles(path, "*.cs", SearchOption.AllDirectories)
            .Where(x => !x.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}"));

        foreach (var file in csFiles)
        {
            var source = File.ReadAllText(file);

            // Skip auto-generated files
            if (source.StartsWith("// <auto-generated>", StringComparison.Ordinal))
                continue;

            var tree = CSharpSyntaxTree.ParseText(source, path: file);
            var root = tree.GetRoot();
            var relativePath = file.Substring(path.Length + 1);

            yield return (relativePath, root);
        }
    }

    internal static Assembly LoadAssembly(AssemblyMetadata assemblyMetadata)
    {
        if (TryLoadAs(assemblyMetadata, AssembliesMetadata.E2ETestsAssembly, out var loadFrom))
            return loadFrom!;
        if (TryLoadAs(assemblyMetadata, AssembliesMetadata.E2ESharedTestsAssembly, out loadFrom))
            return loadFrom!;
        if (TryLoadAs(assemblyMetadata, AssembliesMetadata.WiremockTestsAssembly, out loadFrom))
            return loadFrom!;
        if (TryLoadAs(assemblyMetadata, AssembliesMetadata.InteropTestsAssembly, out loadFrom))
            return loadFrom!;

        return Assembly.Load(new AssemblyName(assemblyMetadata));
    }

    private static bool TryLoadAs(AssemblyMetadata assemblyMetadata, AssemblyMetadata asTarget, out Assembly? result)
    {
        if (!Equals(assemblyMetadata.ToString(), asTarget.ToString()))
        {
            result = null;
            return false;
        }

        var dllFile = Path.Combine(SolutionRoot, "tests", asTarget.ProjectName, OutputSubdirectory, $"{asTarget.Name}.dll");

        if (!File.Exists(dllFile))
            Skip.When(true, $"Assembly {asTarget} has no build output in {OutputSubdirectory}");

        result = Assembly.LoadFrom(dllFile);
        return true;
    }

    private static string FindOutputSubdirectory()
    {
        var projectDirectory = Path.Combine(SolutionRoot, "tests", AssembliesMetadata.TestsAssembly.ProjectName) + Path.DirectorySeparatorChar;
        var baseDirectory = AppContext.BaseDirectory;
        if (!baseDirectory.StartsWith(projectDirectory, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException($"Test output directory '{baseDirectory}' is not under '{projectDirectory}'");

        return baseDirectory.Substring(projectDirectory.Length).TrimEnd(Path.DirectorySeparatorChar);
    }

    private static string FindSolutionRoot()
    {
        var dir = AppContext.BaseDirectory;
        while (dir != null)
        {
            if (File.Exists(Path.Combine(dir, "Snowflake.Data.sln")))
                return dir;

            dir = dir.EndsWith($"{Path.DirectorySeparatorChar}dotnet")
                ? null
                : Directory.GetParent(dir)?.FullName;
        }

        throw new InvalidOperationException("Cannot find solution root directory");
    }
}
